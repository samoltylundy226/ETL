-- PostgreSQL 17 DWH schema for Week 4 banking ETL lab
CREATE SCHEMA IF NOT EXISTS dwh;
CREATE SCHEMA IF NOT EXISTS audit;

CREATE TABLE IF NOT EXISTS dwh.dim_date (
  date_key INTEGER PRIMARY KEY,
  full_date DATE NOT NULL UNIQUE,
  day_of_month SMALLINT NOT NULL,
  month_number SMALLINT NOT NULL,
  month_name VARCHAR(12) NOT NULL,
  quarter_number SMALLINT NOT NULL,
  year_number SMALLINT NOT NULL,
  day_of_week SMALLINT NOT NULL
);

CREATE TABLE IF NOT EXISTS dwh.dim_account (
  account_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_account_id BIGINT NOT NULL UNIQUE,
  source_customer_id BIGINT NOT NULL,
  account_number VARCHAR(24) NOT NULL,
  account_type VARCHAR(30) NOT NULL,
  currency CHAR(3) NOT NULL,
  account_status VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS dwh.dim_transaction_type (
  transaction_type_key SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_type VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS dwh.fact_transaction (
  transaction_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_transaction_id BIGINT NOT NULL UNIQUE,
  account_key BIGINT NOT NULL REFERENCES dwh.dim_account(account_key),
  transaction_type_key SMALLINT NOT NULL REFERENCES dwh.dim_transaction_type(transaction_type_key),
  transaction_date_key INTEGER NOT NULL REFERENCES dwh.dim_date(date_key),
  transaction_ts TIMESTAMP NOT NULL,
  amount NUMERIC(18,2) NOT NULL CHECK (amount >= 0),
  currency CHAR(3) NOT NULL,
  transaction_status VARCHAR(20) NOT NULL,
  counterparty_account_id BIGINT,
  description VARCHAR(255),
  source_updated_at TIMESTAMP,
  etl_batch_id VARCHAR(64) NOT NULL,
  dw_loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_fact_transaction_date ON dwh.fact_transaction(transaction_date_key);
CREATE INDEX IF NOT EXISTS ix_fact_transaction_account ON dwh.fact_transaction(account_key);
CREATE INDEX IF NOT EXISTS ix_fact_transaction_status ON dwh.fact_transaction(transaction_status);

CREATE TABLE IF NOT EXISTS audit.etl_batch_log (
  batch_id VARCHAR(64) PRIMARY KEY,
  pipeline_name VARCHAR(100) NOT NULL,
  source_name VARCHAR(100) NOT NULL,
  started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  finished_at TIMESTAMPTZ,
  status VARCHAR(20) NOT NULL DEFAULT 'RUNNING',
  extracted_count BIGINT NOT NULL DEFAULT 0,
  accepted_count BIGINT NOT NULL DEFAULT 0,
  rejected_count BIGINT NOT NULL DEFAULT 0,
  loaded_count BIGINT NOT NULL DEFAULT 0,
  error_message TEXT
);

INSERT INTO dwh.dim_transaction_type (transaction_type)
VALUES ('DEPOSIT'), ('WITHDRAWAL'), ('TRANSFER'), ('PAYMENT')
ON CONFLICT (transaction_type) DO NOTHING;

INSERT INTO dwh.dim_date
(date_key, full_date, day_of_month, month_number, month_name, quarter_number, year_number, day_of_week)
SELECT TO_CHAR(d::date,'YYYYMMDD')::INTEGER, d::date, EXTRACT(DAY FROM d)::SMALLINT,
EXTRACT(MONTH FROM d)::SMALLINT, TO_CHAR(d,'FMMonth'), EXTRACT(QUARTER FROM d)::SMALLINT,
EXTRACT(YEAR FROM d)::SMALLINT, EXTRACT(ISODOW FROM d)::SMALLINT
FROM generate_series(DATE '2026-10-25', DATE '2026-10-27', INTERVAL '1 day') AS g(d)
ON CONFLICT (date_key) DO NOTHING;

